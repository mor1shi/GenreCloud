const SMALL_WORDS = new Set(['and', 'of', 'the', 'for', 'in', 'on', 'a', 'to', 'with']);

function titleCase(value: string): string {
  return value
    .split(' ')
    .map((word, index) =>
      index > 0 && SMALL_WORDS.has(word) ? word : word.charAt(0).toUpperCase() + word.slice(1),
    )
    .join(' ');
}

export function canonicalGenre(name: string): string {
  const cleaned = name.trim().replace(/\s+/g, ' ');
  const key = normalizeText(cleaned);
  if (ALIASES[key]) return ALIASES[key];
  // MusicBrainz tags are lower-case; only known genres get normalized casing,
  // so free-form Discogs styles keep their original spelling.
  return isMusicBrainzGenre(cleaned) ? titleCase(cleaned) : cleaned;
}

export function isMusicBrainzGenre(name: string): boolean {
  const key = normalizeText(name);
  return MB_GENRES.has(key) || key in ALIASES;
}
