export function yandexGenreLabel(slug?: string): string | null {
  if (!slug) return null;
  const key = normalizeText(slug);
  if (!key) return null;
  const mapped = YANDEX_GENRE_LABELS[key];
  if (mapped) return mapped;
  return null;
}
